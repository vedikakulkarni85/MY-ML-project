# ============================================================
#                  FEATURE ENGINEERING
# ============================================================


# ------------------------------------------------------------
# 19. VEHICLE AGE
# ------------------------------------------------------------

df["vehicle_age"] = (
    df["year"].max() - df["year"]
)

print("\nVehicle Age Created:")

display(
    df[
        ["year", "vehicle_age"]
    ].head(10)
)


# ------------------------------------------------------------
# 20. HORSEPOWER CATEGORY
# ------------------------------------------------------------

df["horsepower_category"] = pd.cut(
    df["horsepower"],
    bins=[0, 100, 150, 1000],
    labels=[
        "Low",
        "Medium",
        "High"
    ]
)

print("\nHorsepower Category Created:")

display(
    df[
        ["horsepower", "horsepower_category"]
    ].head(10)
)


# ------------------------------------------------------------
# 21. WEIGHT CATEGORY
# ------------------------------------------------------------

df["weight_category"] = pd.cut(
    df["weight"],
    bins=[0, 2500, 3500, 5000],
    labels=[
        "Light",
        "Medium",
        "Heavy"
    ]
)

print("\nWeight Category Created:")

display(
    df[
        ["weight", "weight_category"]
    ].head(10)
)


# ============================================================
#                EDA AFTER FEATURE ENGINEERING
# ============================================================


# ------------------------------------------------------------
