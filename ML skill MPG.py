plt.show()


# ============================================================
#                   MACHINE LEARNING
# ============================================================


# ------------------------------------------------------------
# 24. DEFINE FEATURES AND TARGET
# ------------------------------------------------------------

# Target:
# mpg

# Numerical features
numeric_features = [
    "cylinders",
    "displacement",
    "horsepower",
    "weight",
    "acceleration",
    "year",
    "origin"
]

# Categorical feature
categorical_features = [
    "horsepower_category",
    "weight_category"
]

X = df[
    numeric_features +
    categorical_features
]

y = df["mpg"]

print("\nFeatures:")
print(X.columns.tolist())

print("\nTarget:")
print("mpg")


# ------------------------------------------------------------
# 25. TRAIN TEST SPLIT
# ------------------------------------------------------------

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("\nTraining Data Shape:")
print(X_train.shape)

print("\nTesting Data Shape:")
print(X_test.shape)


# ============================================================
#                PREPROCESSING PIPELINE
# ============================================================


# ------------------------------------------------------------
# 26. NUMERICAL SCALING
# ------------------------------------------------------------

numeric_transformer = Pipeline(
    steps=[
        (
            "scaler",
            StandardScaler()
        )
    ]
)


# ------------------------------------------------------------
# 27. CATEGORICAL ENCODING
# ------------------------------------------------------------

categorical_transformer = Pipeline(
    steps=[
        (
            "encoder",
            OneHotEncoder(
                handle_unknown="ignore"
            )
        )
    ]
)


# ------------------------------------------------------------
# 28. COLUMN TRANSFORMER
# ------------------------------------------------------------

preprocessor = ColumnTransformer(
    transformers=[
        (
            "num",
            numeric_transformer,
            numeric_features
        ),
        (
            "cat",
            categorical_transformer,
            categorical_features
        )
    ]
)


# ============================================================
#                 LINEAR REGRESSION MODEL
# ============================================================


# ------------------------------------------------------------
# 29. CREATE PIPELINE
# ------------------------------------------------------------

model = Pipeline(
    steps=[
        (
            "preprocessor",
            preprocessor
        ),
        (
            "regressor",
            LinearRegression()
        )
    ]
)


# ------------------------------------------------------------
# 30. TRAIN MODEL
# ------------------------------------------------------------

model.fit(
    X_train,
    y_train
)

print("\nLinear Regression Model Trained Successfully!")


# ------------------------------------------------------------
# 31. PREDICTION
# ------------------------------------------------------------

y_pred = model.predict(
    X_test
)


# ============================================================
#                    MODEL EVALUATION
# ============================================================


# ------------------------------------------------------------
# 32. CALCULATE METRICS
# ------------------------------------------------------------

mse = mean_squared_error(
    y_test,
    y_pred
)

rmse = np.sqrt(mse)

mae = mean_absolute_error(
    y_test,
    y_pred
)

r2 = r2_score(
    y_test,
    y_pred
)


print("\n" + "=" * 60)
print("LINEAR REGRESSION RESULTS")
print("=" * 60)

print("MSE :", mse)
print("RMSE:", rmse)
print("MAE :", mae)
print("R²  :", r2)


# ============================================================
#                ACTUAL VS PREDICTED
# ============================================================


# ------------------------------------------------------------
# 33. COMPARISON TABLE
# ------------------------------------------------------------

comparison = pd.DataFrame({

    "Actual_MPG": y_test.values,

    "Predicted_MPG": y_pred

})

comparison["Error"] = (
    comparison["Actual_MPG"] -
    comparison["Predicted_MPG"]
)

print("\nActual vs Predicted MPG:")

