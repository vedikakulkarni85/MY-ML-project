# ------------------------------------------------------------
# 36. GET FEATURE NAMES
# ------------------------------------------------------------

trained_preprocessor = (
    model.named_steps["preprocessor"]
)

feature_names = (
    trained_preprocessor
    .get_feature_names_out()
)

