# ============================================================
#                  FEATURE ENGINEERING
# ============================================================


# -----------------------------
# 18. AGE GROUP
# -----------------------------

df["age_group"] = pd.cut(
    df["age"],
    bins=[0, 25, 40, 60, 100],
    labels=[
        "Young",
        "Adult",
        "Middle_Aged",
        "Senior"
    ]
)

print("\nAge Group Created:")
display(
    df[
        ["age", "age_group"]
    ].head(10)
)


# -----------------------------
# 19. TOTAL CAPITAL
# -----------------------------

df["total_capital"] = (
    df["capital_gain"] +
    df["capital_loss"]
)

print("\nTotal Capital Created:")
display(
    df[
        [
            "capital_gain",
            "capital_loss",
            "total_capital"
        ]
    ].head(10)
)


# -----------------------------
# 20. WORK HOURS CATEGORY
# -----------------------------

df["work_hours_category"] = pd.cut(
    df["hours_per_week"],
    bins=[0, 35, 45, 100],
    labels=[
        "Part-Time",
        "Full-Time",
        "Overtime"
    ]
)

print("\nWork Hours Category Created:")
display(
    df[
        [
            "hours_per_week",
            "work_hours_category"
        ]
    ].head(10)
)


# -----------------------------
# 21. EDUCATION LEVEL
# -----------------------------

education_mapping = {

    "Preschool": 0,
    "1st-4th": 1,
    "5th-6th": 2,
    "7th-8th": 3,
    "9th": 4,
    "10th": 5,
    "11th": 6,
    "12th": 7,
    "HS-grad": 8,
    "Some-college": 9,
    "Assoc-voc": 10,
    "Assoc-acdm": 10,
    "Bachelors": 11,
    "Masters": 12,
    "Prof-school": 13,
    "Doctorate": 14

}

df["education_level"] = df["education"].map(
    education_mapping
)

print("\nEducation Level Created:")

display(
    df[
        [
            "education",
            "education_level"
        ]
    ].head(10)
)


# -----------------------------
# 22. BINARY INCOME
# -----------------------------

df["income_binary"] = df["income"].map({
    "<=50K": 0,
    ">50K": 1
})

print("\nBinary Income Created:")

display(
    df[
        [
            "income",
            "income_binary"
        ]
    ].head(10)
)


