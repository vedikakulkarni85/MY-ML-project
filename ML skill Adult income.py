# ============================================================
#                    GROUP ANALYSIS
# ============================================================


# -----------------------------
# 28. INCOME BY EDUCATION
# -----------------------------

education_income = (
    df.groupby("education")["income_binary"]
    .mean()
    .sort_values(ascending=False)
)

print("\nAverage Income Probability by Education:")
print(education_income)


# -----------------------------
# 29. INCOME BY OCCUPATION
# -----------------------------

occupation_income = (
    df.groupby("occupation")["income_binary"]
    .mean()
    .sort_values(ascending=False)
)

print("\nAverage Income Probability by Occupation:")
print(occupation_income)


# -----------------------------
# 30. INCOME BY WORKCLASS
# -----------------------------

workclass_income = (
    df.groupby("workclass")["income_binary"]
    .mean()
    .sort_values(ascending=False)
)

